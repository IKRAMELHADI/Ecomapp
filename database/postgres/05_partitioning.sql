-- ==================================================
-- AquaSave - Partitionnement mensuel des commandes
-- PostgreSQL 16
-- ==================================================

BEGIN;

-- 1. Sécurité : arrêter si les tables contiennent des données
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM orders.orders)
       OR EXISTS (SELECT 1 FROM orders.order_items) THEN
        RAISE EXCEPTION
            'Partitionnement annulé : les tables ne sont pas vides';
    END IF;
END
$$;

-- 2. Supprimer les tables vides concernées
DROP TABLE orders.order_items;
DROP TABLE orders.orders;

-- 3. Créer la table partitionnée
CREATE TABLE orders.orders (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    customer_id INTEGER NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending',
    total_cents INTEGER NOT NULL CHECK (total_cents >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT pk_orders_partitioned
        PRIMARY KEY (id, created_at),

    CONSTRAINT fk_orders_customer
        FOREIGN KEY (customer_id)
        REFERENCES orders.customers(id),

    CONSTRAINT chk_order_status
        CHECK (
            status IN (
                'pending',
                'paid',
                'preparing',
                'shipped',
                'delivered',
                'payment_failed',
                'cancelled'
            )
        )
)
PARTITION BY RANGE (created_at);

-- 4. Créer les partitions mensuelles
-- Les limites sont exprimées en UTC pour être explicites.

DO $$
DECLARE
    month_start DATE;
    month_end DATE;
    partition_name TEXT;
BEGIN
    FOR month_start IN
        SELECT generate_series(
            DATE '2026-01-01',
            DATE '2027-12-01',
            INTERVAL '1 month'
        )::DATE
    LOOP
        month_end := (month_start + INTERVAL '1 month')::DATE;

        partition_name :=
            'orders_' || to_char(month_start, 'YYYY_MM');

        EXECUTE format(
            'CREATE TABLE orders.%I
             PARTITION OF orders.orders
             FOR VALUES FROM (%L) TO (%L)',
            partition_name,
            to_char(month_start, 'YYYY-MM-DD') || ' 00:00:00+00',
            to_char(month_end, 'YYYY-MM-DD') || ' 00:00:00+00'
        );
    END LOOP;
END
$$;

-- 5. Partition de secours pour les dates non couvertes
CREATE TABLE orders.orders_default
PARTITION OF orders.orders DEFAULT;

-- 6. Recréer les lignes de commande
CREATE TABLE orders.order_items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    order_id INTEGER NOT NULL,
    order_created_at TIMESTAMPTZ NOT NULL,

    product_id INTEGER NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price_cents INTEGER NOT NULL
        CHECK (unit_price_cents >= 0),

    CONSTRAINT fk_order_items_order
        FOREIGN KEY (order_id, order_created_at)
        REFERENCES orders.orders(id, created_at)
        ON DELETE CASCADE
);

-- 7. Recréer les index métier
CREATE INDEX idx_orders_customer_date
ON orders.orders(customer_id, created_at DESC);

CREATE INDEX idx_orders_status_date
ON orders.orders(status, created_at DESC);

CREATE INDEX idx_order_items_order
ON orders.order_items(order_id, order_created_at);

COMMIT;